/** Link to a symbol of the API reference generated by dart doc. */
export function apiHref(symbol: string): string {
	if (/^[A-Z]/.test(symbol)) return `/api/scidart/${symbol}-class.html`;
	return `/api/scidart/${symbol}.html`;
}
